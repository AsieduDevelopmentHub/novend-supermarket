#!/usr/bin/env node
/**
 * Bake NOVEND_APP_URL into the Capacitor local boot page so production APKs
 * client-navigate to the same hosted origin Electron uses.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const appUrl = (process.env.NOVEND_APP_URL || "https://novend-pos.vercel.app").replace(/\/$/, "");
// Same entry as Electron / CAPACITOR_MOBILE.md. Unauthenticated → middleware /login.
const entry = "/dashboard";
const dest = join(root, "apps/mobile/www/app-config.js");

writeFileSync(
  dest,
  `/* Generated by scripts/write-mobile-boot.mjs */\n` +
    `window.NOVEND_APP_URL = ${JSON.stringify(appUrl)};\n` +
    `window.NOVEND_APP_ENTRY = ${JSON.stringify(entry)};\n`,
);
console.log(`Wrote ${dest} → ${appUrl}${entry}`);
